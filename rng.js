// Seeded randomness shared by the dataset generator, the benchmark and the
// cold-start sampler. Deterministic so the app, tests and benchmark agree.

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function choice(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

export function randInt(rng, n) {
  return Math.floor(rng() * n);
}

export function permutation(rng, n) {
  const a = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
